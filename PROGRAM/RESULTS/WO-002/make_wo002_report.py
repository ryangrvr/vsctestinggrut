#!/usr/bin/env python3
"""Generate REPORT.md from wo002_results.json (and xcheck_results.json if present).
RULES rule 6: no hand-transcribed numbers. Run from this directory."""
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "wo002_results.json")))
xc_path = os.path.join(here, "xcheck_results.json")
xc = json.load(open(xc_path)) if os.path.exists(xc_path) else None

L = ["# WO-002 — BRI1 copula coordinates under T_mono: REPORT (numbers only)", "",
     f"Grade: **{d['grade']}**. Generated by `make_wo002_report.py` from `wo002_results.json`; "
     "do not edit by hand.", "",
     f"Grid τ = {tuple(d['tau'])}; m₂ = {d['m2']:.12f}.", "",
     "## Exact controls", "", "| Control | Value |", "|---|---|"]
for k, v in d["controls"].items():
    L.append(f"| {k} | {json.dumps(v)} |")
L += ["", "## Free autocorrelation ρ (P0)", ""]
for row in d["rho_free"]:
    L.append("    " + "  ".join(f"{x:+.10f}" for x in row))
L += ["", "## Odd sector: A_abc (third-order normal-score tensor off span{T^(m)}), formal leading "
      "order; copula coordinate = A/N_B", "",
      "| Protocol(component) | A (primary: method A, h = 0.06) | quadrature spread | |A|/spread | GH192 |",
      "|---|---|---|---|---|"]
for k, v in d["odd_channel_A"].items():
    r = v["ratio_to_spread"]
    L.append(f"| {k} | {v['value']:+.10e} | {v['spread']:.2e} | {r:.2e} | {v['GH192']:+.6e} |"
             if r is not None else f"| {k} | {v['value']:+.10e} | 0 | — | {v['GH192']:+.6e} |")
L += ["", "## Even sector: Δρ_ab (normal-score correlation change, formal leading order; "
      "copula coordinate = Δρ/N_B; read via |ρ^N| modulo reflections)", "",
      "| Protocol(pair) | Δρ (primary) | quadrature spread | |Δρ|/spread | GH192 |",
      "|---|---|---|---|---|"]
for k, v in d["even_channel_drho"].items():
    r = v["ratio_to_spread"]
    L.append(f"| {k} | {v['value']:+.10e} | {v['spread']:.2e} | {r:.2e} | {v['GH192']:+.6e} |"
             if r is not None else f"| {k} | {v['value']:+.10e} | 0 | — | {v['GH192']:+.6e} |")
L += ["", "## N_B scaling (cumulant-level coordinates of F at finite N_B, times N_B; trapezoid h = 0.08)", ""]
for p, rows in d["finite_NB"].items():
    comps = list(rows[0]["N_B_times_A"].keys())
    off = [c for c in comps if len(set(c.strip("()").split(","))) > 1]
    L.append(f"**{p} — N_B·A (off-diagonal components)**")
    L.append("")
    L.append("| N_B | " + " | ".join(off) + " |")
    L.append("|---|" + "---|" * len(off))
    for r in rows:
        L.append(f"| {r['N_B']} | " + " | ".join(f"{r['N_B_times_A'][c]:+.6e}" for c in off) + " |")
    L.append("")
    pairs = list(rows[0]["N_B_times_drho"].keys())
    L.append(f"**{p} — N_B·Δρ**")
    L.append("")
    L.append("| N_B | " + " | ".join(pairs) + " |")
    L.append("|---|" + "---|" * len(pairs))
    for r in rows:
        L.append(f"| {r['N_B']} | " + " | ".join(f"{r['N_B_times_drho'][c]:+.6e}" for c in pairs) + " |")
    L.append("")
if xc is not None:
    L += ["## Independent cross-check (separate implementation)", "", "```",
          json.dumps(xc.get("summary", xc), indent=1)[:6000], "```", ""]
L += ["## Preregistered reading (applied mechanically; G2-07)", "",
      f"- P1: {', '.join(d['reading_P1'])}",
      f"- P2: {', '.join(d['reading_P2'])}", "",
      "Outcome 1 (ESCAPE-*) is escape at formal leading order, evidence grade; theorem grade "
      "is OPEN (R1_T_LADDER §9 M5). LEADING-ORDER NULL is not a kill (outcome 2)."]
open(os.path.join(here, "REPORT.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
